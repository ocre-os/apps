const assert=require('node:assert/strict');
const {codex,claude}=require('./quota-adapters.js');
const now=1791800000;
const windows=[{name:'primary',remaining:65,resets_at:now+3600},{name:'secondary',remaining:8,resets_at:now+7200}];
const snapshot={provider:'codex',observed_at:now,complete:true,blocked:false,windows};
const result=codex(snapshot,now);
assert.equal(result.state,'limited');
assert.equal(result.remaining,8);
assert.equal(result.unit,'percent');
assert.equal(result.source,'cli');
assert.equal(result.resets_at,new Date((now+7200)*1000).toISOString());
assert.equal(codex({...snapshot,blocked:true},now).state,'exhausted');
assert.equal(codex({...snapshot,observed_at:now-301},now),null);
assert.equal(codex({...snapshot,complete:false},now),null);
assert.equal(codex({...snapshot,windows:[windows[0]]},now),null);
assert.equal(codex({...snapshot,windows:[windows[0],{...windows[1],remaining:-4}]},now),null);
assert.equal(claude({...snapshot,provider:'claude',blocked:false},now).state,'limited');
assert.equal(claude({...snapshot,provider:'claude',windows:windows.map(w=>({...w,remaining:0}))},now).state,'exhausted');
assert.equal(claude({...snapshot,provider:'claude',observed_at:now-310},now),null);
console.log('OCRE_QUOTA_ADAPTERS_OK');
